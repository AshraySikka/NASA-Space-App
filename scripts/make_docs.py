#!/usr/bin/env python3
"""Fill docs/DEMO_SCRIPT.md and docs/SUBMISSION.md from the processed data, so no count or
range in them is typed by hand. Run by `make ingest`."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
D = ROOT / "data" / "processed"
R = json.loads((D / "ranges.json").read_text())
S = json.loads((D / "sources.json").read_text())
C = json.loads((D / "cards.json").read_text())
T = json.loads((D / "tests.json").read_text())
CFG = json.loads((D / "rating_config.json").read_text())
CH = json.loads((D / "chunks.json").read_text())


def rng(r):
    return "not recorded" if not r else (f"{r['min']:g}" if r["min"] == r["max"] else f"{r['min']:g} to {r['max']:g}")


mat = {m["material_group"]: m for m in R["materials"]}
ser = lambda m, s: next(x for x in mat[m]["series"] if x["series"] == s)  # noqa: E731
sib, nom = ser("SIBAL", "BASS-II"), ser("Nomex", "BASS-II")
sv = ser("SIBAL", "Saffire VI")
verified = sum(1 for t in T if t["evidence_role"] == "verified")
local = [s for s in S if s["local_filename"]]
quench = sib["n_listed_quenched"]
green = next(t for t in T if t["listed_quenched"])
dois = [(c["study"], d["label"].replace(" DOI", ""), d["doi"]) for c in C for d in c["dois"]]

demo = f"""# Demo script

Generated by `scripts/make_docs.py` from `data/processed`. Numbers below are read from the data.

## Three live questions

| # | Type in the chat | What the judge sees |
|---|---|---|
| 1 | `What happened to SIBAL at {green['o2_pct_initial']:g}% oxygen and 5 cm/s?` | Green badge "Inside tested range". Test {green['test_id']} quoted with its page in NASA/TM-20210011385. Click a citation chip, then "Apply to simulator". |
| 2 | `Will this burn on the Moon?` | Red badge "Outside tested data". The answer says there is no direct measurement, lists the nearest microgravity tests, and quotes NASA's FM2 page (Tier 2) and a JAXA leaflet (Tier 3). The scene shows "ESTIMATE, NOT MEASURED". No spread rate anywhere. |
| 3 | `What is the price of bitcoin today?` | Exactly: "Not found in NASA sources I can verify", plus what was searched. |

## 30-second video: shot list

| Time | Shot | Voice-over / subtitle (English subtitles are required) |
|---|---|---|
| 0 to 4 s | Title card on the app's main screen | "Would this fabric burn on the Moon? Has NASA ever tested it there?" |
| 4 to 10 s | Type question 2, red badge appears, scene shows ESTIMATE | "Ask it. The honest answer: never measured at lunar gravity. Here is the closest real evidence." |
| 10 to 17 s | Click a citation chip; Sources drawer opens on the quote and page | "Every statement carries its NASA source, the page, and the exact words." |
| 17 to 24 s | Map tab: drag oxygen from {sib['o2_pct_initial']['max']:g}% upward, crosshair leaves the tested area, badge turns red | "Drag the conditions. {sib['n_tests']} SIBAL tests on the station cover {rng(sib['o2_pct_initial'])}% oxygen. Past that, hatching means no data." |
| 24 to 30 s | Result banner + footer line | "It never says safe. It shows what NASA tested, what happened, and what is still unknown." |

## 7 slides, exact on-screen text

1. **Title.** "EMBER: an evidence finder for spacecraft fire safety" / "Team Apex · NASA Space Apps 2026 · Toronto"
2. **The problem.** "Fire behaves differently in space. Designers ask: has this material been tested at my oxygen level, airflow and gravity?" / "The answers are spread across reports, tables and slides."
3. **What we built.** "Ask a question. Get an answer built only from NASA sources, with the page and the exact quote." / "A code-computed rating: inside tested range, near the edge, or outside tested data."
4. **The data.** "{R['all']['n_tests']} structured tests · {verified} checked row by row against NASA/TM-20210011385 · {len(local)} source files · {len(CH)} searchable passages" / "SIBAL (BASS-II): {sib['n_tests']} tests, {rng(sib['o2_pct_initial'])}% oxygen, airflow {rng(sib['flow_any_cm_s'])} cm/s · Nomex (BASS-II): {nom['n_tests']} tests, {rng(nom['o2_pct_initial'])}% oxygen"
5. **Why you can trust it.** "The AI sees only retrieved passages. Backend code checks every quote and every number, and removes what it cannot confirm." / "Removed statements are listed, not hidden."
6. **What we found.** "Gravity labels in the data: {', '.join(R['gravity_labels'])}. Partial gravity: none." / "Rows with a published flame spread rate: {R['n_spread_rates_published']}. Airflow changed during {sib['n_flow_changed']} of {sib['n_tests']} SIBAL tests, so we plot each test as a path." / "{quench} published quenching cases mark the only boundary we draw."
7. **Next.** "Add results from NASA's FM2 lunar experiment and JAXA FLARE when they are published." / "Extend the row-by-row review beyond the {verified} fabric tests." / "Evidence tool, not a safety certification."
"""
(ROOT / "docs" / "DEMO_SCRIPT.md").write_text(demo)

nasa_sources = "\n".join(f"- {s['title']} ({s['publisher']}{', ' + str(s['year']) if s['year'] else ''}). {s['url']}" + (f" doi:{s['doi']}" if s["doi"] else "") for s in local if s["id"].startswith(("ntrs", "psi", "nasa")))
other_sources = "\n".join(f"- {s['title']} ({s['publisher']}). {s['url']}" + (f" doi:{s['doi']}" if s["doi"] else "") for s in S if s["id"].startswith(("ucl", "nsf", "web-jaxa")))
sub = f"""# Space Apps submission text

Generated by `scripts/make_docs.py` from `data/processed`. Paste into the project form and adjust tone as needed.

## Project name idea

**EMBER: Evidence Mapping for Burning Experiments and Research** (tagline: "Tested, not guessed")

## High-level summary

Designers of spacecraft, suits and habitats need to know whether a material has actually been tested at their oxygen level, airflow, pressure and gravity. We built a research assistant that answers only from NASA data and documents, cites the source and page with the exact quote, and rates the evidence with a rule computed in code: inside tested range, near the edge, or outside tested data. It never calls a material safe. It shows what NASA tested, what was observed, and where nothing has been tested, on a live flammability map and an illustrative flame simulator.

## Project details

- **Data layer.** A reproducible Python pipeline turns NASA's PSI-25 table, the BASS-II summary report, Saffire papers and related documents into {R['all']['n_tests']} structured test rows, {len(CH)} searchable passages and {len(C)} research cards. {verified} fabric rows were checked one by one against NASA/TM-20210011385 and carry a page reference. The pipeline cross-checks the review sheet against Table 7.1 parsed from the PDF, repairs spreadsheet date corruption, flags implausible sensor values and drops duplicate files by hash.
- **Evidence rating.** Code compares the user's conditions with tests of the exact same material. Green needs a test within ±{CFG['match_o2_points']:g} oxygen points and ±{CFG['match_flow_cm_s']:g} cm/s. Airflow is treated as a path, because it changed during {sib['n_flow_changed']} of {sib['n_tests']} SIBAL tests. Gravity that was never tested is always red.
- **Grounded chat.** Retrieval runs in layers: local structured data and BM25 first, then Gemini with Google Search restricted to an allowlist of NASA and primary-source sites, then Claude's web search as a fallback. The model sees only retrieved passages and must return claims with verbatim quotes.
- **Verifier.** Backend code checks each quote against the cited passage, each number against the quote or the cited test row, and re-fetches web sources itself. Failed statements are removed and listed.
- **What the data shows.** SIBAL on the ISS: {sib['n_tests']} tests at {rng(sib['o2_pct_initial'])}% oxygen. Nomex on the ISS: {nom['n_tests']} tests at {rng(nom['o2_pct_initial'])}% oxygen, calibrated airflow not published. One published Saffire VI SIBAL burn at {rng(sv['o2_pct_initial'])}% oxygen and {rng(sv['pressure_kpa'])} kPa. No partial-gravity measurement and no published spread rate in the structured data.
- **Stack.** React, TypeScript, three.js, FastAPI, rank_bm25, Gemini and Claude APIs.

## NASA data used

{nasa_sources}

Dataset identifiers found in the source files:

{chr(10).join(f"- {study}, {label}: https://doi.org/{doi}" for study, label, doi in dois)}

Web context quoted with its read date (not in the local corpus):

- NASA Glenn, Flammability of Materials on the Moon (FM2): https://www.nasa.gov/glenn/glenn-expertise-space-exploration/physical-sciences-program/combustion-science/flammability-of-materials-on-the-moon-fm2/

## Space agency partner and other data

{other_sources}

## Use of artificial intelligence

Claude and Gemini are used at run time to find and draft answers from retrieved NASA passages. AI coding assistance was used to write the application and the ingestion pipeline. No AI output is shown without checks: backend code computes every evidence rating and verifies every statement and number against its source before display. The 3D flame is an illustration and is labelled as such. No NASA logo or insignia is used.

## How accuracy is verified

1. All data in the app comes from files produced by the ingestion script; nothing is typed by hand and there is no sample data.
2. {verified} fabric rows are page-referenced and cross-checked against the report table parsed from the PDF.
3. Every chat statement must quote its source; code rejects statements whose quote or numbers are not in the source.
4. Web sources must be on an allowlist and are re-fetched by the backend to confirm the quote.
5. Automated tests cover the verifier (including a hallucinated number, a wrong page and an off-allowlist URL), the rating, ingestion, and a browser smoke test.
"""
(ROOT / "docs" / "SUBMISSION.md").write_text(sub)
print("wrote docs/DEMO_SCRIPT.md and docs/SUBMISSION.md")
